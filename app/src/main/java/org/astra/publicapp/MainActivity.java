package org.astra.publicapp;

import android.app.Activity;
import android.annotation.SuppressLint;
import android.webkit.JavascriptInterface;
import android.util.Base64;
import android.widget.Toast;
import java.io.OutputStream;
import java.io.IOException;
import android.window.OnBackInvokedDispatcher;
import android.content.pm.ApplicationInfo;
import android.content.Intent;
import android.graphics.Color;
import android.net.Uri;
import android.os.Build;
import android.os.Bundle;
import android.view.View;
import android.view.WindowInsets;
import android.view.WindowManager;
import android.webkit.WebChromeClient;
import android.webkit.WebResourceRequest;
import android.webkit.WebResourceResponse;
import android.webkit.WebSettings;
import android.webkit.WebView;
import android.webkit.WebViewClient;
import android.widget.FrameLayout;

import androidx.webkit.WebViewAssetLoader;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.Collections;

/**
 * Conteneur natif minimal : actifs locaux HTTPS, réseau autorisé seulement pour le géocodage de villes.
 * L'unique pont natif est limité à l'export graphique dans un document choisi par l'utilisateur. Aucun accès aux fichiers existants, comptes ou réseau.
 */
public final class MainActivity extends Activity {
    private static final String HOST = "appassets.androidplatform.net";
    private static final String BASE = "https://" + HOST + "/assets/";
    private WebView webView;
    private static final int REQUEST_EXPORT_CHART = 7291;
    private byte[] pendingChartBytes;

    private static boolean isAttributionLink(Uri uri) {
        if (uri == null || !"https".equalsIgnoreCase(uri.getScheme())) return false;
        String host = uri.getHost();
        return "open-meteo.com".equalsIgnoreCase(host) || "www.open-meteo.com".equalsIgnoreCase(host);
    }

    private static boolean isGeocodingApi(Uri uri) {
        return uri != null && "https".equalsIgnoreCase(uri.getScheme())
                && "geocoding-api.open-meteo.com".equalsIgnoreCase(uri.getHost())
                && "/v1/search".equals(uri.getPath())
                && uri.getUserInfo() == null;
    }

    private static boolean isLocalAsset(Uri url) {
        return url != null
                && "https".equalsIgnoreCase(url.getScheme())
                && HOST.equalsIgnoreCase(url.getHost())
                && url.getEncodedPath() != null
                && url.getEncodedPath().startsWith("/assets/")
                && !url.getEncodedPath().contains("..")
                && !url.getEncodedPath().contains("%2e")
                && !url.getEncodedPath().contains("%2E");
    }

    private static WebResourceResponse forbidden() {
        return new WebResourceResponse(
                "text/plain", "UTF-8", 403, "Forbidden",
                Collections.singletonMap("Cache-Control", "no-store"),
                new ByteArrayInputStream("Blocked".getBytes(StandardCharsets.UTF_8))
        );
    }


    /**
     * Only allows SVG/PNG generated by local JS. Android opens a system
     * create-document dialog; no data is transmitted to remote services.
     * Even if JS is compromised, this bridge cannot read existing files.
     */
    private final class ChartExportBridge {
        @JavascriptInterface
        public void saveChart(String fileName, String mime, String base64) {
            if (fileName == null || mime == null || base64 == null) return;
            if (!("image/png".equals(mime) || "image/svg+xml".equals(mime))) return;
            String extension = "image/png".equals(mime) ? ".png" : ".svg";
            if (!fileName.matches("^ASTRA-theme-[a-z-]{1,60}\\.(png|svg)$")
                    || !fileName.endsWith(extension) || base64.length() > 14000000) return;
            final byte[] bytes;
            try {
                bytes = Base64.decode(base64, Base64.DEFAULT);
                if (bytes.length < 50 || bytes.length > 10000000) return;
            } catch (IllegalArgumentException e) { return; }
            runOnUiThread(() -> {
                // Require the first-party asset page, not just a matching host.
                if (webView == null || !((BASE + "index.html").equals(webView.getUrl()))
                        || pendingChartBytes != null) return;
                pendingChartBytes = bytes;
                Intent intent = new Intent(Intent.ACTION_CREATE_DOCUMENT);
                intent.addCategory(Intent.CATEGORY_OPENABLE);
                intent.setType(mime);
                intent.putExtra(Intent.EXTRA_TITLE, fileName);
                try {
                    startActivityForResult(intent, REQUEST_EXPORT_CHART);
                } catch (Exception e) {
                    pendingChartBytes = null;
                    Toast.makeText(MainActivity.this, "Enregistrement indisponible", Toast.LENGTH_LONG).show();
                }
            });
        }
    }

    @Override
    protected void onActivityResult(int requestCode, int resultCode, Intent data) {
        super.onActivityResult(requestCode, resultCode, data);
        if (requestCode != REQUEST_EXPORT_CHART) return;
        byte[] bytes = pendingChartBytes;
        pendingChartBytes = null;
        if (resultCode != RESULT_OK || data == null || data.getData() == null || bytes == null) return;
        Uri destination = data.getData();
        try (OutputStream stream = getContentResolver().openOutputStream(destination, "w")) {
            if (stream == null) throw new IOException("No document output stream");
            stream.write(bytes);
            stream.flush();
            Toast.makeText(this, "Roue astrologique enregistrée", Toast.LENGTH_SHORT).show();
        } catch (Exception e) {
            Toast.makeText(this, "Échec de l’enregistrement de l’image", Toast.LENGTH_LONG).show();
        }
    }

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        getWindow().setStatusBarColor(Color.rgb(248, 245, 252));
        getWindow().setNavigationBarColor(Color.rgb(248, 245, 252));
        getWindow().getDecorView().setSystemUiVisibility(
                View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR | View.SYSTEM_UI_FLAG_LIGHT_NAVIGATION_BAR
        );

        FrameLayout root = new FrameLayout(this);
        root.setBackgroundColor(Color.rgb(248, 245, 252));
        // Android 15+ impose l'edge-to-edge : réserver les zones des barres système.
        // Android 15+ draws behind the status/navigation bars. The keyboard is
        // another inset: without it the journal and date fields can be covered
        // by Samsung One UI's IME even though the system bars look correct.
        getWindow().setSoftInputMode(WindowManager.LayoutParams.SOFT_INPUT_ADJUST_RESIZE);
        root.setOnApplyWindowInsetsListener((view, insets) -> {
            if (Build.VERSION.SDK_INT >= 30) {
                android.graphics.Insets bars = insets.getInsets(
                        WindowInsets.Type.systemBars() | WindowInsets.Type.displayCutout()
                );
                android.graphics.Insets ime = insets.getInsets(WindowInsets.Type.ime());
                int bottom = Math.max(bars.bottom, ime.bottom);
                root.setPadding(bars.left, bars.top, bars.right, bottom);
            } else {
                root.setPadding(insets.getSystemWindowInsetLeft(), insets.getSystemWindowInsetTop(),
                        insets.getSystemWindowInsetRight(), insets.getSystemWindowInsetBottom());
            }
            return insets;
        });

        webView = new WebView(this);
        webView.addJavascriptInterface(new ChartExportBridge(), "ASTRA_CHART_EXPORT");
        root.addView(webView, new FrameLayout.LayoutParams(-1, -1));
        setContentView(root);
        root.requestApplyInsets();

        WebSettings settings = webView.getSettings();
        settings.setJavaScriptEnabled(true); // requis pour l'interface ASTRA
        settings.setDomStorageEnabled(true); // journal local
        // Honor viewport width=device-width rather than a legacy desktop viewport.
        settings.setUseWideViewPort(true);
        settings.setLoadWithOverviewMode(false);
        settings.setAllowFileAccess(false);
        settings.setAllowContentAccess(false);
        settings.setAllowFileAccessFromFileURLs(false);
        settings.setAllowUniversalAccessFromFileURLs(false);
        settings.setJavaScriptCanOpenWindowsAutomatically(false);
        settings.setSupportMultipleWindows(false);
        settings.setMixedContentMode(WebSettings.MIXED_CONTENT_NEVER_ALLOW);
        settings.setGeolocationEnabled(false);
        settings.setSafeBrowsingEnabled(true);
        webView.setWebChromeClient(new WebChromeClient()); // confirm() pour restaurer le journal

        boolean debugging = (getApplicationInfo().flags & ApplicationInfo.FLAG_DEBUGGABLE) != 0;
        WebView.setWebContentsDebuggingEnabled(debugging);

        WebViewAssetLoader loader = new WebViewAssetLoader.Builder()
                .setDomain(HOST)
                .addPathHandler("/assets/", new WebViewAssetLoader.AssetsPathHandler(this))
                .build();
        webView.setWebViewClient(new WebViewClient() {
            @Override
            public boolean shouldOverrideUrlLoading(WebView view, WebResourceRequest request) {
                Uri uri = request.getUrl();
                if (isAttributionLink(uri)) {
                    try { startActivity(new Intent(Intent.ACTION_VIEW, uri)); }
                    catch (Exception ignored) { /* Browser not installed; do not navigate in the WebView. */ }
                    return true;
                }
                return !isLocalAsset(uri);
            }

            @Override
            public WebResourceResponse shouldInterceptRequest(WebView view, WebResourceRequest request) {
                Uri uri = request.getUrl();
                // Autoriser seulement la recherche explicite d'une ville via HTTPS.
                // Les navigations externes restent bloquées ci-dessus.
                if ("GET".equalsIgnoreCase(request.getMethod()) && isGeocodingApi(uri)) return null;
                if (!isLocalAsset(uri)) return forbidden();
                WebResourceResponse response = loader.shouldInterceptRequest(uri);
                return response != null ? response : forbidden();
            }
        });
        if (Build.VERSION.SDK_INT >= 33) {
            getOnBackInvokedDispatcher().registerOnBackInvokedCallback(
                OnBackInvokedDispatcher.PRIORITY_DEFAULT, this::navigateBackOrFinish
            );
        }
        webView.loadUrl(BASE + "index.html");
    }

    private void navigateBackOrFinish() {
        final WebView page = webView;
        if (page == null) { finish(); return; }
        // ASTRA is a single-page UI. WebView history alone cannot close a
        // sheet, exit zoom, or return from Explorer: ask that UI first.
        if ((BASE + "index.html").equals(page.getUrl())) {
            page.evaluateJavascript(
                    "(function(){try{return Boolean(window.ASTRA_HANDLE_BACK && window.ASTRA_HANDLE_BACK())}catch(e){return false}})()",
                    handled -> {
                        if ("true".equals(handled) || isFinishing()) return;
                        if (webView != null && webView.canGoBack()) webView.goBack();
                        else finish();
                    }
            );
        } else if (page.canGoBack()) {
            page.goBack();
        } else {
            finish();
        }
    }

    @SuppressLint("GestureBackNavigation")
    @Override
    public void onBackPressed() {
        navigateBackOrFinish();
    }

    @Override
    protected void onDestroy() {
        pendingChartBytes = null;
        if (webView != null) {
            webView.destroy();
            webView = null;
        }
        super.onDestroy();
    }
}